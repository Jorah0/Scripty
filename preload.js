'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('scripty', {
  info: inv('app:info'),
  getConfig: inv('config:get'),
  setSettings: inv('config:setSettings'),
  setProvider: inv('config:setProvider'),
  setKey: inv('config:setKey'),
  models: inv('ai:models'),
  stream: inv('ai:stream'),
  cancel: inv('ai:cancel'),
  onAI: (cb) => { const h = (e, d) => cb(d); ipcRenderer.on('ai:event', h); return () => ipcRenderer.removeListener('ai:event', h); },
  listProjects: inv('projects:list'),
  loadProject: inv('projects:load'),
  saveProject: inv('projects:save'),
  deleteProject: inv('projects:delete'),
  importFile: inv('file:import'),
  exportFile: inv('file:export'),
  reveal: inv('file:reveal'),
  sfxList: inv('sfx:list'),
  sfxImport: inv('sfx:import'),
  sfxUpdate: inv('sfx:update'),
  sfxRemove: inv('sfx:remove'),
  sfxAddGenerated: inv('sfx:addGenerated'),
  setHotkeys: inv('hotkeys:set'),
  onHotkey: (cb) => { const h = (e, a) => cb(a); ipcRenderer.on('hotkey', h); return () => ipcRenderer.removeListener('hotkey', h); },
  openExternal: inv('shell:openExternal'),
  setTheme: inv('win:setTheme'),
  openData: inv('data:open'),
  labGet: inv('lab:get'),
  labSet: inv('lab:set'),
  labHardware: inv('lab:hardware'),
  labCatalog: inv('lab:catalog'),
  labPull: inv('lab:pull'),
  labCancelPull: inv('lab:cancelPull'),
  labExamples: inv('lab:examples'),
  labAddExample: inv('lab:addExample'),
  labPatchExample: inv('lab:patchExample'),
  labRemoveExample: inv('lab:removeExample'),
  labExportKit: inv('lab:exportKit'),
  onLab: (cb) => { const h = (e, d) => cb(d); ipcRenderer.on('lab:event', h); return () => ipcRenderer.removeListener('lab:event', h); },
  remoteStatus: inv('remote:status'),
  remoteEnable: inv('remote:enable'),
  remotePort: inv('remote:port'),
  remoteNewCode: inv('remote:newCode'),
  remoteRevoke: inv('remote:revoke'),
  remotePushUpdate: inv('remote:pushUpdate'),
  onRemoteCommand: (cb) => { const h = (e, d) => cb(d); ipcRenderer.on('remote:command', h); return () => ipcRenderer.removeListener('remote:command', h); },
  sendRemoteState: (s) => ipcRenderer.send('remote:state', s),
});
